"""Write docs/EXPERIMENTS_AND_RESULTS.md from the loaded results (called by build_report.py)."""
from __future__ import annotations

from datetime import datetime
from pathlib import Path


def _table(header, rows):
    out = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def _img(run_id, name, alt):
    return f"![{alt}](../reports/data/{run_id}/{name})"


def write(v, T, tabs, path: Path) -> None:
    runs = v["runs"]
    rid = {k: r["run_id"] for k, r in runs.items()}
    env = v["e1_env"]
    ov = v["e1_overhead"]
    c1, c2, c3, c4 = (v["e1_cfg"], v["e2_cfg"], v["e3_cfg"], v["e4_cfg"])
    md = []
    a = md.append
    a("# Experiments and results")
    a("")
    a(f"*Generated by `reports/build_report.py` on {datetime.now():%Y-%m-%d %H:%M} from the result files of the "
      "runs listed below. Do not edit numbers by hand — re-run the experiments and the builder instead.*")
    a("")
    a("## Runs used")
    a(_table(["Experiment", "Run id", "Profile", "Evidence", "Duration (s)"],
             [[k.upper(), r["run_id"], r["config"]["profile"], r["evidence"], r["duration_s"]] for k, r in runs.items()]))
    a("")
    a("Each run's full output (config.json, metadata.json, results.json, CSV tables, PNG graphs) is copied "
      "to `reports/data/<run_id>/`; the originals are in `results/<experiment>/<run_id>/`.")
    a("")
    a("## Environment")
    a(_table(["Item", "Value"], [
        ["CPU", f"{env['cpu']} ({env['logical_cpus']} logical CPUs)"], ["Memory", f"{env['memory_gb']} GB"],
        ["OS", env["os"]], ["Python", env["python"]],
        ["Libraries", ", ".join(f"{k} {x}" for k, x in env["libraries"].items())],
        ["Redis", f"{env['engines'].get('redis_version')} ({env['engines'].get('redis_mode')}), "
                  f"Docker Desktop; experiment DB endpoints {', '.join(env['engines'].get('redis_endpoints', []))}"],
        ["Git commit", env.get("git_commit") or "not a git repository"],
    ]))
    a("")
    a("E1 was run from the CLI with the API server, MongoDB and Cassandra stopped to reduce background load.")
    a("")
    a("## How to reproduce")
    a("```powershell\ndocker compose up -d\npowershell -ExecutionPolicy Bypass -File scripts\\run_experiments.ps1 "
      "-Experiment all -Profile default\n.\\.venv\\Scripts\\python reports\\build_report.py\n```")
    a("Profiles are defined in `configs/experiments.yaml` (`quick` for a fast check, `default` = the sizes "
      "below, `large` for longer runs).")
    a("")

    # ------------------------------------------------------------------ E1
    a("## E1 — Throughput and latency (live Redis)")
    a("**Protocol.** Python re-implementation of YCSB core workloads [Cooper et al. 2010]: A = 50 % read / 50 % "
      f"update, B = 95/5, C = 100 % read; scrambled Zipfian key popularity (θ = {c1['zipf_theta']}); "
      f"{c1['records']:,} records × {c1['value_bytes']} B; {c1['operations']:,} operations per run after "
      f"{c1['warmup']:,} warm-up reads; {c1['repetitions']} repetitions; one client thread; runs interleaved "
      "rep → workload → configuration. Latency is measured per operation around the client call; throughput = "
      "operations / wall time.")
    a("")
    a("**Configurations.** `direct` — redis-py on one Redis instance; `hanf` — full HANF pipeline (router, "
      "hash ring over 4 shards, consistency lookup, telemetry), security off; `+ sync ML` — Isolation Forest "
      "scoring inline for each completed 100-request window; `+ batched ML` — 20 windows per model call, "
      "inline; `+ async ML` — background worker.")
    a("")
    a("**Output files:** `e1_runs.csv` (every run), `e1_summary.csv`, `e1_pipeline_overhead.csv`, "
      "`e1_throughput.png`, `e1_p99_latency.png`.")
    a("")
    a(_table(["Workload", "Configuration", "Throughput (ops/s, mean ± SD)", "Δ vs direct", "p50 (µs)", "p99 (µs)"],
             tabs["e1"]))
    a("")
    if ov:
        a("**HANF CPU cost without network I/O** (µs per request, from `e1_pipeline_overhead.csv`):")
        a(_table(["Component", "µs"], [[k, x] for k, x in ov.items() if k != "samples"]))
        a("")
    a("**All default-profile E1 runs** (Δ throughput vs direct, %). The report uses the most recent run "
      f"whose worst direct-Redis CV (SD/mean) is below {v['e1_rule']:.2f}; this rule was fixed before the "
      "last run was inspected.")
    allr = v["e1_all_runs"]
    keys = [k for k in allr[0] if k not in ("run_id", "direct_cv_max", "duration_s", "used_in_report")]
    a(_table(["Run", "Direct CV (worst)", "Duration (s)", "Used"] + keys,
             [[r["run_id"], r["direct_cv_max"], r["duration_s"], "yes" if r["used_in_report"] else ""]
              + [r.get(k, "") for k in keys] for r in allr]))
    a("")
    if v["e1_overhead_source"] != rid["e1"]:
        a(f"*The no-I/O pipeline measurement comes from run {v['e1_overhead_source']} (it was added to E1 after "
          "the selected run).*")
        a("")
    a(_img(rid["e1"], "e1_throughput.png", "E1 throughput"))
    a(_img(rid["e1"], "e1_p99_latency.png", "E1 p99 latency"))
    a("")
    a("**Interpretation.**")
    for p in T["e1"]:
        a("")
        a(p)
    a("")

    # ------------------------------------------------------------------ E2
    a("## E2 — Adaptive sharding (algorithmic + live Redis)")
    a("**Protocol.** (1) Remapping: MD5-based ring, "
      f"{c2['remap_keys']:,} keys, add one node to {', '.join(f'{a_}→{b_}' for a_, b_ in c2['node_counts'])} nodes, "
      f"modulo vs consistent hashing with {c2['vnode_options']} virtual nodes, {c2['ring_seeds']} ring seeds "
      "(different node names). Imbalance = max / mean key count before the change. (2) Rebalancing: "
      f"{c2['rebalance_keys']:,} keys, {c2['rebalance_nodes']} nodes × {c2['rebalance_vnodes']} vnodes, "
      f"{c2['rebalance_requests']:,} requests drawn from Zipf {c2['zipf_exponents']}, {c2['rebalance_rounds']} "
      "rounds of `v_i ← max(16, round(v_i·(1 − 0.5·(L_i/mean(L) − 1))))`. (3) Live migration: "
      f"{c2['live_keys']:,} keys of {c2['live_value_bytes']} random bytes into 4 Redis shards, add shard 5 through "
      f"the ShardManager, verify every {c2['verify_every']}th key byte-for-byte at its new owner, check every "
      "key sits on its ring owner, reconcile totals.")
    a("")
    a("**Output files:** `e2_remap_runs.csv`, `e2_remap_summary.csv`, `e2_rebalance.csv`, "
      "`e2_live_migration.csv`, `e2_sharding.png`, `e2_live_migration.png`.")
    a("")
    a(_table(["Scheme", "4→5 nodes (%)", "10→11 nodes (%)", "Imbalance, 4 nodes"], tabs["e2"]))
    a("")
    reb_rows = [[r["zipf_exponent"], r["round"], r["max_over_mean"], r["cv"],
                 r.get("keys_moved_by_next_adjustment_pct", "–")] for r in v["e2_reb"]]
    a(_table(["Zipf s", "Round", "Max/mean load", "CV", "Keys moved by next adjustment (%)"], reb_rows))
    a("")
    m = v["e2_live"]["migration"]
    a(_table(["Shard", "Keys before", "Keys after"],
             [[s, m["keys_before"][s], m["keys_after"][s]] for s in m["keys_before"]]
             + [["**Total**", m["total_before"], m["total_after"]]]))
    a("")
    a(_img(rid["e2"], "e2_sharding.png", "E2 remapping and rebalancing"))
    a(_img(rid["e2"], "e2_live_migration.png", "E2 live migration"))
    a("")
    a("**Interpretation.**")
    for p in T["e2"]:
        a("")
        a(p)
    a("")

    # ------------------------------------------------------------------ E3
    a("## E3 — ML security monitor (synthetic traffic)")
    a("**Protocol.** Seeded generator of 100-request windows: normal traffic (reads/writes/updates on Zipf-hot "
      "keys, ~3 % misses, occasional logins and small scans, 5 % of windows with benign look-alike text such as "
      "\"Union Square\"), injection (operator/SQL-keyword payloads), exfiltration (large SCANs) and brute-force "
      "login, 30 % of attacks as low-intensity *subtle* variants that stay under the static thresholds. "
      f"Train {c3['train_windows']:,} normal windows; validation {c3['val_normal']:,} normal + "
      f"{c3['val_per_attack']}/attack (contamination chosen by best F1 among {c3['contaminations']}); test "
      f"{c3['test_normal']:,} normal + {c3['test_per_attack']}/attack; seeds {c3['seeds']}. Evasion sweep: "
      f"{c3['intensity_windows']} windows per point with {c3['intensity_levels']} of requests replaced by "
      "attack requests at a normal request rate. Latency: single-window and 20-window model calls.")
    a("")
    a("Features per window: request rate, key diversity, mean payload bytes, failure ratio, injection-pattern "
      "ratio, SCAN ratio. Metrics: precision = TP/(TP+FP), recall = TP/(TP+FN), F1 = 2PR/(P+R), "
      "FPR = FP/(FP+TN), per-attack recall, recall on subtle attacks.")
    a("")
    a("**Output files:** `e3_test_metrics_by_seed.csv`, `e3_summary.csv`, `e3_selected_model.csv`, "
      "`e3_evasion_sweep.csv`, `e3_scoring_latency.csv`, `e3_detection.png`, `e3_scores_evasion.png`.")
    a("")
    a(_table(["Method", "Precision", "Recall", "F1", "FPR %", "Injection %", "Exfiltration %", "Brute force %",
              "Subtle %", "Times selected"], tabs["e3"]))
    a("")
    a(_table(["Seed", "Selected c", "Precision", "Recall", "F1", "FPR"],
             [[s["seed"], s["selected_contamination"], s["precision"], s["recall"], s["f1"], s["fpr"]]
              for s in v["e3_selected"]]))
    a("")
    a(_table(["Seed", "Single window (ms)", "p95 (ms)", "20-window call (ms)", "Per window in batch (ms)"],
             [[x["seed"], x["single_window_mean"], x["single_window_p95"], x["batch20_call_mean"],
               x["batch20_per_window"]] for x in v["e3_latency"]]))
    a("")
    levels = c3["intensity_levels"]
    a(_table(["Attack"] + [f"{100 * l:g} %" for l in levels],
             [[k] + [f"{v['e3_sweep_fn'](k, l) * 100:.0f}" for l in levels]
              for k in ("injection", "exfiltration", "bruteforce")]))
    a("*Evasion sweep: Isolation Forest recall (%) by share of attack requests in the window; static rules "
      "detect none of these windows below 30 %.*")
    a("")
    a(_img(rid["e3"], "e3_detection.png", "E3 detection"))
    a(_img(rid["e3"], "e3_scores_evasion.png", "E3 scores and evasion"))
    a("")
    a("**Interpretation.**")
    for p in T["e3"]:
        a("")
        a(p)
    a("")

    # ------------------------------------------------------------------ E4
    a("## E4 — Adaptive consistency (simulation)")
    a("**Model.** N = 3 replicas (regions A, B, C); writer in A (mean RTT 2/30/110 ms), reader in B "
      "(30/2/80 ms). RTT sample = base × congestion (remote links) × LogNormal(0, 0.25). Write latency = W-th "
      "smallest writer RTT; replica i applies the write at rtt_w[i]/2. Read issued Exp(15 ms) after the ack, "
      "contacts the R replicas closest to the reader, latency = slowest contacted RTT; stale if no contacted "
      "replica has applied the write when the read arrives (t_read + rtt_r[j]/2). Controller: Monte-Carlo "
      f"({c4['mc_samples']:,} samples) over 7 (W,R) profiles, choose min mean latency s.t. P(stale) ≤ SLO "
      f"({c4['slo'] * 100:g} %), else ALL/ALL; re-selects each phase from the congestion observed in the previous "
      f"phase. Timeline {c4['phases']}, {c4['ops_per_phase']:,} operations per phase (half writes, half reads), "
      f"seeds {c4['seeds']}. Sweeps: read delay {c4['read_delays_ms']} ms; SLO {[s * 100 for s in c4['slos']]} %.")
    a("")
    a("**Output files:** `e4_strategies_by_seed.csv`, `e4_summary.csv`, `e4_adaptive_phases.csv`, "
      "`e4_sensitivity_read_delay.csv`, `e4_sensitivity_slo.csv`, `e4_consistency.png`, `e4_timeline.png`, "
      "`e4_sensitivity.png`.")
    a("")
    a(_table(["Strategy", "Write (ms)", "Read (ms)", "Mean (ms)", "p95 (ms)", "Stale reads (%)"], tabs["e4"]))
    a("")
    a(_table(["Read delay (ms)", "Strategy", "Mean (ms)", "Stale (%)"],
             [[r["read_delay_ms"], r["strategy"], r["mean_ms"], r["stale_pct"]] for r in v["e4_sens_delay"]]))
    a("")
    a(_table(["SLO (%)", "Mean (ms)", "p95 (ms)", "Stale (%)", "Profiles chosen"],
             [[r["slo_pct"], r["mean_ms"], r["p95_ms"], r["stale_pct"], r["profiles"]] for r in v["e4_sens_slo"]]))
    a("")
    a(_img(rid["e4"], "e4_consistency.png", "E4 consistency"))
    a(_img(rid["e4"], "e4_timeline.png", "E4 timeline"))
    a(_img(rid["e4"], "e4_sensitivity.png", "E4 sensitivity"))
    a("")
    a("**Interpretation.**")
    for p in T["e4"]:
        a("")
        a(p)
    a("")

    # ------------------------------------------------------------------ historical
    a("## Historical reference (Review II report — not produced by this implementation)")
    a("Copied from the Review II report (single-core VM, earlier prototype). Shown only for comparison.")
    a("")
    a(_table(["Exp.", "Metric", "Review II value"], [
        ["E1", "Throughput A/B/C, direct (ops/s)", "16,004 / 17,209 / 22,341"],
        ["E1", "Δ vs direct: routing / sync ML / batched ML (A)", "+5.1 % / −53.2 % / −12.5 %"],
        ["E2", "Remapped 4→5 / 10→11, CH v=128 (modulo)", "20.7 / 8.1 % (79.8 / 90.8 %)"],
        ["E2", "Rebalancing CV round 0 → 5", "0.092 → 0.006"],
        ["E2", "Live migration 4→5, 50,000 keys", "10,454 moved in 0.31 s, 0 mismatches"],
        ["E3", "Static rules P / R / F1", "1.000 / 0.653 / 0.790"],
        ["E3", "IF c=0.02 P / R / F1 / FPR (tuned on test set)", "0.899 / 0.995 / 0.945 / 2.2 %"],
        ["E4", "Mean latency ONE / QUORUM / ALL / adaptive (ms)", "4.5 / 54.2 / 239.3 / 26.9"],
        ["E4", "Stale reads ONE / adaptive (%)", "69.8 / 0.009"],
    ]))
    a("")
    a("**Why the new numbers differ.** E1: different machine and Docker Desktop networking (every request "
      "crosses a VM boundary), and the HANF path now includes the full router, consistency lookup and telemetry "
      "publication. E2: same algorithm; differences are within the seed-to-seed spread now reported. E3: the "
      "contamination is now chosen on a validation split and the traffic generator was rewritten, so values "
      "are not directly comparable. E4: see the last E4 paragraph — Review II's QUORUM read latency is not "
      "reachable under its own stated model.")
    a("")
    a("## Threats to validity and limitations")
    a(T["threats"])
    a("")
    a("See also [KNOWN_LIMITATIONS.md](KNOWN_LIMITATIONS.md).")
    path.write_text("\n".join(md) + "\n", encoding="utf-8")
